"""Pre-generate the full-time recap of the demo match (text + audio) for every favourite club x persona, so the demo never waits.

    HTG_ENV=azure python -m htg.recap.pregen --seed 7

The server asks for exactly these recaps at the end of period 2 (same `t`, same fingerprint), so they come from the cache.
The sentences go to `eval/results/recap_fulltime.md` for reading before listening; stale cached recaps of this match are deleted.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from htg.env import load_env
from htg.generate import OUT_DIR, generate
from htg.narration.service import PERSONAS, known_names
from htg.recap.agent import AUDIO_DIR, CACHE_DIR, LANGS, fingerprint, get_recap_model, write_recap
from htg.recap.tools import MatchRecord

OUT = Path(__file__).resolve().parents[2] / "eval" / "results" / "recap_fulltime.md"
FAVOURITES = (None, "HOME", "AWAY")


def full_time_t(rec: MatchRecord) -> float:
    return next(e["t"] for e in rec.events if e["type"] == "period_end" and e["period"] == 2)


def main(seed: int) -> None:
    load_env()
    match_dir = OUT_DIR / f"match_{seed:04d}"
    rec = MatchRecord.load(match_dir if match_dir.exists() else generate(seed))
    model = get_recap_model()
    if model is None:
        raise SystemExit("needs HTG_ENV=azure and Foundry credentials")
    from htg.speech.azure import AzureSpeech, clip_name

    speech, names, t = AzureSpeech(cache_dir=AUDIO_DIR), known_names(rec.meta), full_time_t(rec)
    lines = [f"# Full-time recaps, seed {seed} (t = {t:.0f} s)", "", "Generated by `python -m htg.recap.pregen`. Read before listening. "
             "Source `agent` = written by the Foundry recap agent and passed the Verifier; `template` = fallback.", ""]
    keep: set[str] = set()
    clips: set[str] = set()
    for fav in FAVOURITES:
        for persona in PERSONAS:
            r = write_recap(rec, t, 0, fav, persona, model, names)
            keep.add(f"{fingerprint(rec.meta['match_id'], t, 0, fav, persona, model.name)}.json")
            for lang in LANGS:
                if speech.synthesize(" ".join(r[lang]), lang) is None:
                    print(f"TTS failed: {fav} {persona} {lang}")
                clips.add(clip_name(" ".join(r[lang]), speech.voices[lang]))
            lines += [f"## favourite {fav or 'none'}, {persona}", "",
                      f"tools: {', '.join(r['tools_used']) or '-'}; source EN {r['source']['en']}, TR {r['source']['tr']}; "
                      f"cached {r['cached']}", ""]
            lines += [f"- EN: {' '.join(r['en'])}", f"- TR: {' '.join(r['tr'])}", ""]
            if r["reasons"]:
                lines += [f"- Verifier (first pass): {json.dumps(r['reasons'], ensure_ascii=False)}", ""]
            print(fav, persona, r["source"], r.get("latency_s"))
    for f in CACHE_DIR.glob("*.json"):  # this folder only holds pregenerated full-time recaps; live recaps are not committed
        if f.name not in keep:
            f.unlink()
    for f in AUDIO_DIR.glob("*.mp3"):
        if f.name not in clips:
            f.unlink()
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(OUT.parents[2])}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--seed", type=int, default=7)
    main(ap.parse_args().seed)
